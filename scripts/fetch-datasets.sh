#!/usr/bin/env bash
# Fetch LeetCode Database problem list and mysqlSchemas; write datasets/*/setup.sql and manifest.json.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DATASETS_DIR="${ROOT}/datasets"
MANIFEST_PATH="${DATASETS_DIR}/manifest.json"
GRAPHQL_URL="${LEETCODE_GRAPHQL_URL:-https://leetcode.com/graphql/}"
REQUEST_DELAY="${FETCH_DELAY_SEC:-0.12}"
PRESERVE_SETUP="${PRESERVE_SETUP:-1}"

LIST_QUERY='query problemsetQuestionList($categorySlug: String, $limit: Int, $skip: Int, $filters: QuestionListFilterInput) {
  problemsetQuestionList: questionList(categorySlug: $categorySlug, limit: $limit, skip: $skip, filters: $filters) {
    total: totalNum
    questions: data {
      frontendQuestionId: questionFrontendId
      title
      titleSlug
      difficulty
    }
  }
}'

DETAIL_QUERY='query questionContent($titleSlug: String!) {
  question(titleSlug: $titleSlug) {
    questionFrontendId
    title
    mysqlSchemas
  }
}'

graphql() {
  local query="$1"
  local variables="${2:-{}}"
  curl -sS "${GRAPHQL_URL}" \
    -H 'Content-Type: application/json' \
    -H 'User-Agent: leetcode-sql-toolkit/1.0 (community dataset generator)' \
    --data "$(jq -n --arg q "${query}" --argjson v "${variables}" '{query: $q, variables: $v}')"
}

die() {
  echo "fetch-datasets: $*" >&2
  exit 1
}

write_setup_from_schemas() {
  local id="$1"
  local title="$2"
  local schemas_json="$3"
  local out="$4"

  {
    printf '%s\n\n' "-- LeetCode ${id} — ${title} (MySQL schema from LeetCode, generated by fetch-datasets.sh)"
    echo "${schemas_json}" | jq -r '.[] | select(test("^\\s*[Tt]runcate\\b"; "i") | not) | if test("^\\s*[Cc]reate\\s") then
      gsub("^[Cc]reate table [Ii]f [Nn]ot [Ee]xists "; "CREATE TABLE IF NOT EXISTS ")
      | gsub("^CREATE TABLE IF NOT EXISTS "; "CREATE TABLE IF NOT EXISTS ")
      else . end'
  } >"${out}"
}

fetch_all_questions() {
  local skip=0
  local limit=100
  local total=-1
  local acc="[]"

  while [[ "${total}" -lt 0 || "${skip}" -lt "${total}" ]]; do
    local resp
    resp="$(graphql "${LIST_QUERY}" "$(jq -n --argjson skip "${skip}" --argjson limit "${limit}" \
      '{categorySlug: "database", skip: $skip, limit: $limit, filters: {}}')")"
    if echo "${resp}" | jq -e '.errors' >/dev/null 2>&1; then
      die "GraphQL list error: $(echo "${resp}" | jq -c '.errors')"
    fi
    total="$(echo "${resp}" | jq '.data.problemsetQuestionList.total')"
    local batch
    batch="$(echo "${resp}" | jq '.data.problemsetQuestionList.questions')"
    acc="$(jq -s 'add' <(echo "${acc}") <(echo "${batch}"))"
    skip=$((skip + limit))
    sleep "${REQUEST_DELAY}"
  done

  echo "${acc}" | jq 'sort_by(.frontendQuestionId | tonumber)'
}

main() {
  command -v curl >/dev/null || die "curl is required"
  command -v jq >/dev/null || die "jq is required"

  local old_manifest="{}"
  if [[ -f "${MANIFEST_PATH}" ]]; then
    old_manifest="$(cat "${MANIFEST_PATH}")"
  fi

  echo "==> Fetching database problem list from LeetCode..."
  local questions
  questions="$(fetch_all_questions)"
  local count
  count="$(echo "${questions}" | jq 'length')"
  echo "==> Found ${count} problems. Fetching mysqlSchemas (delay ${REQUEST_DELAY}s)..."

  local manifest_entries="[]"
  local ok=0 skipped=0 failed=0
  local i=0

  while IFS= read -r row; do
    i=$((i + 1))
    local id title slug difficulty dir setup_path
    id="$(echo "${row}" | jq -r '.frontendQuestionId')"
    title="$(echo "${row}" | jq -r '.title')"
    slug="$(echo "${row}" | jq -r '.titleSlug')"
    difficulty="$(echo "${row}" | jq -r '.difficulty')"
    dir="$(printf '%04d-%s' "${id}" "${slug}")"
    setup_path="${DATASETS_DIR}/${dir}/setup.sql"

    printf '[%s/%s] %s — %s ... ' "${i}" "${count}" "${id}" "${title}"

    if [[ "${PRESERVE_SETUP}" == "1" && -f "${setup_path}" ]]; then
      echo "preserve setup.sql"
      skipped=$((skipped + 1))
    else
      local detail schemas
      detail="$(graphql "${DETAIL_QUERY}" "$(jq -n --arg slug "${slug}" '{titleSlug: $slug}')")"
      if echo "${detail}" | jq -e '.errors' >/dev/null 2>&1; then
        echo "FAIL (graphql)"
        failed=$((failed + 1))
        sleep "${REQUEST_DELAY}"
        continue
      fi
      schemas="$(echo "${detail}" | jq '.data.question.mysqlSchemas // []')"
      if [[ "$(echo "${schemas}" | jq 'length')" == "0" ]]; then
        echo "SKIP (no mysqlSchemas)"
        failed=$((failed + 1))
        sleep "${REQUEST_DELAY}"
        continue
      fi
      mkdir -p "${DATASETS_DIR}/${dir}"
      write_setup_from_schemas "${id}" "${title}" "${schemas}" "${setup_path}"
      echo "wrote setup.sql"
      ok=$((ok + 1))
      sleep "${REQUEST_DELAY}"
    fi

    local desc has_seed=0
    desc="$(echo "${old_manifest}" | jq -r --arg id "${id}" '.datasets[]? | select((.id | tostring) == $id) | .description // empty')"
    if [[ -z "${desc}" ]]; then
      desc="LeetCode sample schema and data for ${title}."
    fi
    if [[ -f "${DATASETS_DIR}/${dir}/seed.sql" ]]; then
      has_seed=1
    fi

    if [[ "${has_seed}" == "1" ]]; then
      manifest_entries="$(echo "${manifest_entries}" | jq \
        --arg id "${id}" \
        --arg title "${title}" \
        --arg directory "${dir}" \
        --arg difficulty "${difficulty}" \
        --arg desc "${desc}" \
        '. + [{
          id: $id,
          title: $title,
          directory: $directory,
          file: "setup.sql",
          seed: "seed.sql",
          difficulty: $difficulty,
          description: $desc
        }]')"
    else
      manifest_entries="$(echo "${manifest_entries}" | jq \
        --arg id "${id}" \
        --arg title "${title}" \
        --arg directory "${dir}" \
        --arg difficulty "${difficulty}" \
        --arg desc "${desc}" \
        '. + [{
          id: $id,
          title: $title,
          directory: $directory,
          file: "setup.sql",
          difficulty: $difficulty,
          description: $desc
        }]')"
    fi
  done < <(echo "${questions}" | jq -c '.[]')

  echo "==> Writing ${MANIFEST_PATH} (${count} datasets)..."
  jq -n \
    --argjson datasets "${manifest_entries}" \
    '{
      version: 1,
      engine: "mysql",
      datasets: ($datasets | sort_by(.id | tonumber))
    }' >"${MANIFEST_PATH}"

  echo "==> Done. setup.sql written: ${ok}, preserved: ${skipped}, failed/skipped schema: ${failed}"
  echo "Run: docker compose exec cli leetcode validate"
}

main "$@"
